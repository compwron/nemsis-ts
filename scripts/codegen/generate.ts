/** Generate `src/generated/` (schema model + document types) from fetched NEMSIS XSDs. */
import {
	mkdirSync,
	readdirSync,
	readFileSync,
	rmSync,
	writeFileSync,
} from "node:fs";
import { join } from "node:path";
import { isDeepStrictEqual } from "node:util";
import type { DatasetName, SimpleType } from "../../src/schema/types.ts";
import { LOCK_PATH, REPO_ROOT, readLock, SPEC_DIR } from "../lib/spec.ts";
import { readDefinedList } from "./lists.ts";
import { emitDatasetTypes, emitSimpleTypes } from "./types.ts";
import { readSchema } from "./xsd.ts";

/** Namespace each dataset's document types are exported under, e.g. `v3_5_1.EMS.PatientCareReport`. */
const NAMESPACES: Record<DatasetName, string> = {
	EMSDataSet: "EMS",
	DEMDataSet: "DEM",
	StateDataSet: "State",
};

const DATASETS: readonly DatasetName[] = [
	"EMSDataSet",
	"DEMDataSet",
	"StateDataSet",
];
export const GENERATED_DIR: string = join(REPO_ROOT, "src", "generated");

/** `3.5.1.251001CP2` → `v3_5_1` */
export function versionDir(version: string): string {
	const m = /^(\d+)\.(\d+)\.(\d+)\./.exec(version);
	if (!m) throw new Error(`Unexpected version ${version}`);
	return `v${m[1]}_${m[2]}_${m[3]}`;
}

const header = (version: string, commit: string) =>
	`// Generated by scripts/codegen.ts from NEMSIS nemsis_public ${version} (${commit}). Do not edit.\n`;

export interface GenerateOptions {
	lockPath?: string;
	specDir?: string;
	outDir?: string;
	log?: (message: string) => void;
}

export function generate(options: GenerateOptions = {}): void {
	const {
		lockPath = LOCK_PATH,
		specDir = SPEC_DIR,
		outDir = GENERATED_DIR,
	} = options;
	const log = options.log ?? console.log;
	const lock = readLock(lockPath);
	rmSync(outDir, { recursive: true, force: true });
	const indexLines: string[] = [];
	const mapLines: string[] = [];
	const typeLines: string[] = [];

	for (const [version, { commit }] of Object.entries(lock.versions)) {
		const xsdDir = join(specDir, version, "XSDs", "NEMSIS_XSDs");
		const fetched = readFileSync(
			join(specDir, version, ".commit"),
			"utf8",
		).trim();
		if (fetched !== commit)
			throw new Error(
				`.spec/${version} is at ${fetched}, lock says ${commit}; re-run spec:fetch`,
			);

		const dir = versionDir(version);
		const out = join(outDir, dir);
		mkdirSync(join(out, "types"), { recursive: true });
		const simpleTypes: Record<string, SimpleType> = {};

		for (const dataset of DATASETS) {
			const { root, simpleTypes: types } = readSchema(
				join(xsdDir, `${dataset}_v3.xsd`),
				dataset,
			);
			for (const [name, t] of Object.entries(types)) {
				const prev = simpleTypes[name];
				if (prev && !isDeepStrictEqual(prev, t))
					throw new Error(
						`${version}: simpleType ${name} differs between datasets`,
					);
				simpleTypes[name] = t;
			}
			writeFileSync(
				join(out, `${dataset}.ts`),
				`${header(version, commit)}import type { GroupElement } from "../../schema/types.ts";\n\n` +
					`export const ${dataset}: GroupElement = ${JSON.stringify(root, null, "\t")};\n`,
			);
			writeFileSync(
				join(out, "types", `${dataset}.ts`),
				`${header(version, commit)}import type { Leaf, NillableLeaf } from "../../../schema/values.ts";\n` +
					`import type * as codes from "./codes.ts";\n\n${emitDatasetTypes(root)}`,
			);
		}

		const sorted = Object.fromEntries(
			Object.entries(simpleTypes).sort(([a], [b]) =>
				a < b ? -1 : a > b ? 1 : 0,
			),
		);
		writeFileSync(
			join(out, "simpleTypes.ts"),
			`${header(version, commit)}import type { SimpleType } from "../../schema/types.ts";\n\n` +
				`export const simpleTypes: Readonly<Record<string, SimpleType>> = ${JSON.stringify(sorted, null, "\t")};\n`,
		);
		writeFileSync(
			join(out, "types", "codes.ts"),
			`${header(version, commit)}\n${emitSimpleTypes(sorted)}`,
		);
		writeFileSync(
			join(out, "types", "index.ts"),
			`${header(version, commit)}export type * as codes from "./codes.ts";\n` +
				DATASETS.map(
					(d) => `export type * as ${NAMESPACES[d]} from "./${d}.ts";\n`,
				).join(""),
		);
		typeLines.push(`export type * as ${dir} from "./${dir}/types/index.ts";\n`);
		writeFileSync(
			join(out, "index.ts"),
			`${header(version, commit)}import type { VersionSchema } from "../../schema/types.ts";\n` +
				DATASETS.map((d) => `import { ${d} } from "./${d}.ts";\n`).join("") +
				`import { simpleTypes } from "./simpleTypes.ts";\n\n` +
				`export const schema: VersionSchema = {\n\tversion: "${version}",\n\tsimpleTypes,\n\tdatasets: { ${DATASETS.join(", ")} },\n};\n`,
		);
		const listsDir = join(specDir, version, "DefinedLists");
		const lists = readdirSync(listsDir, { withFileTypes: true })
			.filter((d) => d.isDirectory())
			.map((d) => d.name)
			.sort()
			.map((name) =>
				readDefinedList(
					readFileSync(join(listsDir, name, `${name}.xml`), "utf8"),
					name,
				),
			);
		writeFileSync(
			join(out, "lists.ts"),
			`${header(version, commit)}import type { DefinedList } from "../../lists/types.ts";\n\n` +
				`export const lists: readonly DefinedList[] = ${JSON.stringify(lists, null, "\t")};\n`,
		);
		indexLines.push(`import { schema as ${dir} } from "./${dir}/index.ts";\n`);
		mapLines.push(`\t"${version}": ${dir},\n`);
		log(
			`${version} → src/generated/${dir} (${Object.keys(sorted).length} simple types)`,
		);
	}

	writeFileSync(
		join(outDir, "index.ts"),
		`// Generated by scripts/codegen.ts. Do not edit.\nimport type { NemsisVersion } from "../index.ts";\nimport type { VersionSchema } from "../schema/types.ts";\n${indexLines.join("")}\n` +
			`export const schemas: Readonly<Record<NemsisVersion, VersionSchema>> = {\n${mapLines.join("")}};\n`,
	);
	writeFileSync(
		join(outDir, "types.ts"),
		`// Generated by scripts/codegen.ts. Do not edit.\n${typeLines.join("")}`,
	);
}
